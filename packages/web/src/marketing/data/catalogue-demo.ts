import type { CatalogueProduct, ProductMedia } from "./catalogue";
import { DEMO_IMG, type DemoImageKey } from "./demo-images";

function money(pkr: number): string {
  return `PKR ${pkr.toLocaleString("en-PK")}`;
}

function mediaFrom(urls: readonly string[], name: string): ProductMedia[] {
  return urls.slice(0, 3).map((url, i) => ({
    id: `m${i + 1}`,
    type: "image" as const,
    url,
    alt: `${name} — view ${i + 1}`,
    zoomUrl: url.replace(/w=\d+/, "w=2400"),
  }));
}

/** Rotate image set so sibling demos in the same subcategory don't share one hero. */
function rotateUrls(urls: readonly string[], salt: string): string[] {
  if (urls.length <= 1) return [...urls];
  const offset =
    [...salt].reduce((acc, ch) => acc + ch.charCodeAt(0), 0) % urls.length;
  return [...urls.slice(offset), ...urls.slice(0, offset)];
}

type Spec = { label: string; value: string };

type DemoDef = {
  readonly id: string;
  readonly name: string;
  readonly category: string;
  readonly collection: string;
  readonly summary: string;
  readonly pricePkr: number;
  readonly imageKey: DemoImageKey;
  readonly taxonomySlugs: readonly string[];
  readonly tags: readonly string[];
  readonly dimensions: string;
  readonly material: string;
  readonly color: string;
  readonly specs: readonly Spec[];
  readonly finishes?: readonly string[];
};

function build(def: DemoDef): CatalogueProduct {
  const urls = rotateUrls(DEMO_IMG[def.imageKey], def.id);
  const hero = urls[0]!;
  const media = mediaFrom(urls, def.name);
  return {
    id: def.id,
    name: def.name,
    category: def.category,
    collection: def.collection,
    summary: def.summary,
    pricePkr: def.pricePkr,
    priceFrom: money(def.pricePkr),
    image: hero,
    featured: false,
    taxonomySlugs: def.taxonomySlugs,
    tags: def.tags,
    warranty: "3–5 years structural",
    availability: "Demo catalogue — made to order",
    leadTime: "4–8 weeks",
    brand: "AFH Demo",
    material: def.material,
    color: def.color,
    rating: 4.5 + (def.pricePkr % 5) * 0.08,
    dimensions: def.dimensions,
    specs: def.specs,
    media,
    // Magnifier + 360 hooks: gallery uses zoomUrl; spin uses short frame list of same product images
    spinFrames: [urls[0]!, urls[1] ?? urls[0]!, urls[2] ?? urls[0]!, urls[0]!],
    models: {},
    variants: [
      { id: `${def.id}-c1`, label: def.color, group: "color", swatch: "#8a7a62", mediaIds: ["m1"] },
      { id: `${def.id}-c2`, label: "Ink", group: "color", swatch: "#2a3238", mediaIds: ["m2"] },
      { id: `${def.id}-f1`, label: def.finishes?.[0] ?? "Natural oil", group: "finish" },
      { id: `${def.id}-f2`, label: def.finishes?.[1] ?? "Matte lacquer", group: "finish" },
      { id: `${def.id}-mat`, label: def.material.split("/")[0]!.trim(), group: "material" },
    ],
    downloads: [
      { label: "Spec sheet (placeholder)", url: "/catalogue.pdf", kind: "spec" },
      { label: "Brochure (placeholder)", url: "/catalogue.pdf", kind: "brochure" },
    ],
  };
}

